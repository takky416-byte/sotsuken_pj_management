
const Q = ({ q, children }: { q: string; children: React.ReactNode }) => (
  <details className="card"><summary><strong>{q}</strong></summary><div className="form">{children}</div></details>
);

/** 使い方。学生用と教員用で内容を分ける。 */
export function Help({ role }: { role: 'student' | 'teacher' }) {
  return role === 'student' ? <StudentHelp /> : <TeacherHelp />;
}

function StudentHelp() {
  return (
    <>
      <h2>使い方</h2>
      <p className="hint">困ったら、まずここを見てください。それでも解決しなければ、先生に連絡してください。</p>
      <Q q="日報の書き方">
        <ol>
          <li>授業日に「日報」を開きます。</li>
          <li>今日取り組んだタスクにチェックを入れ、それぞれに<strong>一言</strong>を書きます(一言は必須です)。</li>
          <li>困っていることがあれば書きます(空でもかまいません)。</li>
          <li>提出します。<strong>その日のうちは、何度でも直せます。</strong>日をまたぐと直せません。</li>
        </ol>
        <p>欠席の扱いは、先生が入力します。日報が出ていなくても、本人が責められるものではなく、状況の確認に使います。</p>
      </Q>
      <Q q="WBS(タスク)の使い方">
        <ul>
          <li>タスクは、チームの誰でも追加・変更できます。「大項目 → 中項目 → 小項目」の3階層です。</li>
          <li>自分の担当は、タスクを開いて「担当」に自分を選びます。複数人でも、空欄でもかまいません。</li>
          <li>状態は「未着手 / 進行中 / 完了 / 保留」。着手したら進行中、終わったら完了にします。</li>
          <li>消したタスクは、あとから元に戻せます。</li>
          <li>資料はGoogleドライブに置き、タスクの「リンク」に貼ります。ファイルのアップロードはできません。</li>
        </ul>
      </Q>
      <Q q="ガント">
        <p><strong>ガント</strong>で、チームの予定の全体像を見られます。棒の長さはタスクの開始日〜終了日です。日付は、ガントの「日付を入力する」にチェックを入れると、一覧で入れられます(開始日だけ入れると、1日のタスクになります)。赤い縦線が今日、◆は締め切りなどの予定です。</p>
      </Q>
      <Q q="チームのようす・ありがとう">
        <p>「チーム」で、直近3週間の、日報の提出(連続日数🔥)、担当・完了・期限超過、ミーティングの約束の達成が、メンバーごとに見られます。点数や順位ではなく、チームで状況を見るための目安です。</p>
        <p>助けてもらったときは、「👏 ありがとう」で、1日3回まで、一言を添えて送れます(送った本人は取り消せます)。ありがとうは、チームの貢献が見える材料になります。</p>
      </Q>
      <Q q="配色を変える">
        <p>画面の右上の「🎨」で、配色(ポップ・オーシャン・ミント・サンセット・クラシック)を選べます。選んだ配色は、この端末のブラウザに保存されます。</p>
      </Q>
      <Q q="ミーティング画面">
        <p>週1回(木曜2限)、1チーム10分。この画面を、先生と同じディスプレイで見ながら話します。前回決めたこと、今週の活動、WBSの進み具合、決めることが並びます。</p>
      </Q>
      <Q q="リマインドのメール">
        <p>授業日の16:30ごろ(木曜は10:45ごろ)、日報が未提出の人に、先生のアドレスから「卒研PJ管理(自動送信)」として届きます。届かないときは、迷惑メールを確認してください。</p>
      </Q>
      <Q q="誰が何を見られる?">
        <ul>
          <li>先生は、<strong>すべてのチームのすべての内容</strong>を見られます。</li>
          <li>他のチームの内容は、学生には見えません。</li>
          <li>先生だけが見るメモがあります。学生には表示されません。</li>
        </ul>
      </Q>
      <Q q="ログインできない・画面がおかしい">
        <ul>
          <li>Safari または Chrome で開いてください(LINEやメールのアプリ内ブラウザでは失敗することがあります)。</li>
          <li>@trident.ac.jp のアカウントで入ってください。</li>
          <li>画面が古いときは、ページを再読み込みしてください。</li>
          <li>「権限がありません」と出るときは、名簿の登録を確認しますので、先生に連絡してください。</li>
        </ul>
      </Q>
    </>
  );
}

function TeacherHelp() {
  return (
    <>
      <h2>使い方(教員)</h2>
      <p className="hint">運用開始の手順は、リポジトリの docs/launch-checklist.md にもあります。</p>
      <Q q="毎週の流れ">
        <ol>
          <li>授業日の16:30ごろ(木曜は10:45ごろ)に、リマインドが自動で届きます(Apps Script)。</li>
          <li>「チーム」で、提出状況と「要確認」(2回連続未提出、担当なしの期限超過)を見ます。</li>
          <li>木曜2限は「ミーティング」から、チームを順に開いて10分ずつ。共有ディスプレイには学生に見せてよい内容だけが出ます。</li>
          <li>結果は、ミーティング画面で記録します。直すときは、チーム詳細の「ミーティング記録」です。</li>
        </ol>
      </Q>
      <Q q="新しいチームを始める(キックオフ)">
        <p>「チーム」→ 該当チーム →「キックオフ」で、企画名と共有フォルダを入れます。雛形の大項目と、取り込んだ案が作られます(再実行しても増えません)。</p>
      </Q>
      <Q q="関与・貢献の確認">
        <p>チーム詳細の「関与」タブで、メンバーごとの目安(日報の提出と連続日数、日報で触れたタスク、担当・完了・期限超過、約束の達成、ありがとうの送受信)を見られます。確認したほうがよい点は、名前の下に出ます(学生には出ません)。点数には換算せず、成績の参考資料として、教員が判断します。</p>
        <p>ミーティングの「次の1週間でやること」には、担当者(約束した人)を付けられます。次回の冒頭で、誰の約束が果たされたかが分かります。前回の未完了は、「引き継ぐ」でまとめて持ち越せます。</p>
      </Q>
      <Q q="日報・欠席">
        <p>日報は授業日のみ。学生は当日中だけ直せます。欠席は「欠席」から教員だけが入力します。運用開始日と、チーム内の日報閲覧は「設定」で変えられます。</p>
      </Q>
      <Q q="授業日・ミーティング・マイルストーン">
        <p>「カレンダー」で、授業日の追加・削除・時限・備考、ミーティングの有無(どの曜日でも)、CSV一括追加、マイルストーンの追加・編集ができます。リマインドも、この授業日を見て送ります。</p>
      </Q>
      <Q q="バックアップから復元する">
        <p>「書き出し」→「バックアップから復元する」で、JSONファイルを選びます。範囲(すべて/チームごと)を選んで「内容を確認する」を押すと、何件が上書き・新規になるかが出ます。復元の直前の状態は、自動でダウンロードされるので、取り消しもできます。バックアップにない文書(バックアップのあとに増えたもの)は消えません。</p>
      </Q>
      <Q q="学生の画面を確認する">
        <p>「学生の画面」で、チームと学生を選ぶと、その学生と同じ画面を閲覧のみで見られます。指導の参考にしてください。</p>
      </Q>
      <Q q="データの書き出し・バックアップ">
        <p>「書き出し」で、全データのJSONと、CSV(タスク・日報・ミーティング記録・名簿・予定・教員メモ)を保存できます。JSONは、同じページの「バックアップから復元する」で戻せます。バックアップは、Apps Script の `setupBackup` を実行すると、毎日、Googleドライブの「バックアップ」フォルダ(共有は「制限付き」にしてください)に自動で保存されます。</p>
      </Q>
      <Q q="教員専用のもの">
        <p>教員メモ(チーム詳細の専用タブ)は、学生に見えません。コメントは学生にも見えます。ミーティング画面は学生に見せる前提です。</p>
      </Q>
    </>
  );
}
