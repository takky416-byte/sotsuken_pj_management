/** 開いた画面のパスから、ガイドの段階の番号。わからなければ 0 (はじめに)。 */
export function stepForPath(pathname: string): number {
  const first = pathname.split('/').filter(Boolean)[0] ?? '';
  const seg = first === 'meeting' ? 'report' : first; // ミーティングは、PJ分析から始める (同じ段階)
  const i = TOUR.findIndex((s) => s.screen === seg);
  return i >= 0 ? i : 0;
}

